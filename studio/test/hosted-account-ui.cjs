'use strict';
// Run with Electron. Uses a disposable profile and synthetic public account
// state; never reads a real wallet, signs a message, or contacts a provider.
const { app } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const { AgentStore } = require('../agent/agent-store.cjs');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'reach-account-ui-'));
app.setPath('userData', dir);
app.commandLine.appendSwitch('force-device-scale-factor', '1');
fs.writeFileSync(path.join(dir, 'settings.json'), JSON.stringify({ theme: 'dark', telemetrySources: [], connections: [] }));
const fixture = new AgentStore(path.join(dir, 'agents.json')).create({ name: 'Menu fixture', dir });
let win; const errors = [];
app.on('browser-window-created', (_event, window) => {
  win = window; setImmediate(() => window.removeAllListeners('ready-to-show'));
  window.webContents.on('console-message', (_event, level, message) => { if (level >= 3) errors.push(message); });
});
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const run = code => win.webContents.executeJavaScript(code, true);
const timeout = setTimeout(() => { console.error('Account UI timed out'); app.exit(1); }, 120000);
(async () => {
  console.log('Account UI: loading isolated Studio');
  await import(pathToFileURL(path.resolve(__dirname, '../main.mjs')).href);
  console.log('Account UI: waiting for Electron');
  await app.whenReady();
  console.log('Account UI: Electron ready');
  while (!win || win.webContents.isLoading()) await delay(50);
  await run("showTab('home')"); await delay(150);
  assert.equal(await run("document.querySelector('#account-menu').hidden"), true);
  await run("document.querySelector('#account-menu-button').click()");
  assert.equal(await run("document.querySelector('#account-menu-button').getAttribute('aria-expanded')"), 'true');
  assert.equal(await run("document.activeElement.id"), 'account-menu-tab-account');
  assert.equal(await run("document.querySelectorAll('#home-account-service').length"), 1);
  assert.equal(await run("document.querySelector('#account-menu-panel-account').contains(document.querySelector('#home-account-service'))"), true);
  assert.equal(await run("document.querySelector('#home-account-connect').disabled"), true);
  assert.equal(await run("document.querySelector('#home-account-service').value"), 'https://unbent-semicolon-hermit.ngrok-free.dev');
  const account = { status: 'connected', baseUrl: 'https://fixture.invalid', connectionId: 'reach_hosted', secureStorageAvailable: true,
    account: { id: 'fixture', walletAddress: '0x0000000000000000000000000000000000000001', plan: { name: 'Professional', status: 'active' },
      allowedModels: [{ id: 'CodeGPT test model', name: 'CodeGPT test model' }, { id: 'Free endpoint test model', name: 'Free endpoint test model' }],
      allowance: { includedRemaining: '1200000', prepaidRemaining: '3000000', reserved: '10000', totalRemaining: '4190000', debt: '0' },
      rchBalance: { status: 'available', decimals: 18, chainId: 1, balanceBaseUnits: '269565909309000000001' } },
    config: { redemptionEnabled: true, tokensPerRch: '1000000', chainId: 11155111 } };
  win.webContents.send('account:state', account); await delay(100);
  assert.equal(await run("document.querySelector('#home-account-plan').textContent"), 'Professional');
  assert.equal(await run("document.querySelector('#home-allowance-included').textContent"), '1,200,000');
  assert.equal(await run("document.querySelectorAll('#home-account-models span').length"), 2);
  assert.equal(await run("document.querySelector('#home-account-use').disabled"), false);
  assert.equal(await run("document.querySelector('#home-wallet-balance').textContent"), '269.565909309000000001 RCH');
  await run("document.querySelector('#home-account-service').value='https://draft.invalid'; document.querySelector('#home-account-service').dispatchEvent(new Event('input')); document.querySelector('#account-menu-close').click()");
  assert.equal(await run("document.activeElement.id"), 'account-menu-button');
  win.webContents.send('account:state', account); await delay(60);
  await run("document.querySelector('#account-menu-button').click()");
  assert.equal(await run("document.querySelector('#home-account-service').value"), 'https://draft.invalid');
  win.setContentSize(1440, 1050); await delay(80);
  fs.writeFileSync(path.join(dir, 'account-wide.png'), (await win.capturePage()).toPNG());
  await run("document.querySelector('#account-menu-tab-usage').click()");
  await run("document.querySelector('#home-redemption-amount').value='2'; document.querySelector('#home-redemption-amount').dispatchEvent(new Event('input'))");
  assert.equal(await run("document.querySelector('#home-redemption-start').disabled"), false);
  win.webContents.send('account:state', { ...account, config: { ...account.config, redemptionEnabled: false } }); await delay(80);
  assert.equal(await run("document.querySelector('#home-redemption-start').disabled"), true);
  assert.match(await run("document.querySelector('#home-redemption-rate').textContent"), /verified market quote/);
  assert.doesNotMatch(await run("document.querySelector('#home-redemption-rate').textContent"), /1,000,000/);
  win.webContents.send('account:state', account); await delay(80);
  await run("document.dispatchEvent(new KeyboardEvent('keydown', {key:'Escape',bubbles:true})); document.querySelector('#account-menu-button').click()");
  assert.equal(await run("document.querySelector('#home-redemption-amount').value"), '2');
  assert.equal(await run("document.querySelector('#account-menu-tab-usage').getAttribute('aria-selected')"), 'true');
  fs.writeFileSync(path.join(dir, 'usage-wide.png'), (await win.capturePage()).toPNG());
  await run("openSettingsPanel('budgeting')");
  assert.equal(await run("document.querySelector('.page.active').id"), 'page-home');
  assert.equal(await run("document.querySelector('#account-menu-panel-settings').contains(document.querySelector('#page-settings'))"), true);
  await run("document.querySelector('#budget-maxRounds').value='137'; document.querySelector('#budget-maxRounds').dispatchEvent(new Event('input', {bubbles:true})); document.querySelector('#account-menu-close').click(); document.querySelector('#account-menu-button').click()");
  await delay(80);
  assert.equal(await run("document.querySelector('#budget-maxRounds').value"), '137');
  await run("document.querySelector('#account-menu-tab-account').click(); document.querySelector('#account-menu-tab-settings').click()"); await delay(80);
  assert.equal(await run("document.querySelector('#budget-maxRounds').value"), '137');
  fs.writeFileSync(path.join(dir, 'settings-wide.png'), (await win.capturePage()).toPNG());
  // The window's production minimum width is larger; lower it for dropdown QA.
  win.setMinimumSize(480, 520);
  win.setContentSize(600, 700); await delay(100);
  for (const section of ['account', 'usage', 'settings']) {
    await run(`document.querySelector('#account-menu-tab-${section}').click()`); await delay(60);
    const geometry = await run(`(() => { const p=document.querySelector('#account-menu-panel-${section}'), m=document.querySelector('#account-menu').getBoundingClientRect(), b=document.querySelector('#account-menu-button').getBoundingClientRect(); return { noOverflow:p.scrollWidth<=p.clientWidth+1, withinViewport:m.left>=0&&m.right<=innerWidth&&m.bottom<=innerHeight, bubbleVisible:b.left>=0&&b.right<=innerWidth, scrollable:p.scrollHeight>p.clientHeight }; })()`);
    assert.equal(geometry.noOverflow, true, section + ' horizontal overflow');
    assert.equal(geometry.withinViewport, true, section + ' clipped dropdown');
    assert.equal(geometry.bubbleVisible, true, section + ' clipped bubble');
    assert.equal(geometry.scrollable, true, section + ' should scroll at narrow height');
    fs.writeFileSync(path.join(dir, section + '-narrow.png'), (await win.capturePage()).toPNG());
  }
  await run("document.querySelector('#account-menu-tab-settings').dispatchEvent(new KeyboardEvent('keydown',{key:'Home',bubbles:true}))");
  assert.equal(await run("document.activeElement.id"), 'account-menu-tab-account');
  await run("document.querySelector('#home-title').dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}))");
  assert.equal(await run("document.querySelector('#account-menu').hidden"), true);
  await run("document.querySelector('#account-menu-button').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true}))");
  assert.equal(await run("document.querySelector('#account-menu').hidden"), false);
  assert.equal(await run("document.activeElement.id"), 'account-menu-tab-account');
  win.webContents.send('account:state', { ...account, account: { ...account.account, plan: { status: 'none' } } }); await delay(80);
  assert.equal(await run("document.querySelector('#home-redemption-start').disabled"), false);
  assert.equal(await run("document.querySelector('#home-account-use').disabled"), false);
  assert.equal(await run("document.querySelector('#home-account-plan').textContent"), 'RCH prepaid access');
  win.webContents.send('account:state', account); await delay(80);
  assert.equal(await run("document.querySelector('#home-redemption-status').textContent"), '');
  win.webContents.send('account:state', { ...account, status: 'connecting', account: null }); await delay(80);
  assert.equal(await run("document.querySelector('#home-account-cancel').hidden"), false);
  assert.equal(await run("document.querySelector('#home-redemption-start').disabled"), true);
  win.webContents.send('account:state', { ...account, status: 'expired', account: null }); await delay(80);
  assert.equal(await run("document.querySelector('#home-account-connect').disabled"), false);
  assert.equal(await run("document.querySelector('#home-allowance-included').textContent"), '—');
  assert.equal(await run("document.querySelector('#home-wallet-balance').textContent"), '—');
  await run("showTab('projects')");
  assert.equal(await run("document.querySelector('#account-menu').hidden"), true);
  await run("openSettingsPanel('connection')");
  assert.equal(await run("document.querySelector('.page.active').id"), 'page-projects');
  await run("document.querySelector('#account-menu-close').click(); document.querySelector('#rail-settings').click()"); await delay(60);
  assert.equal(await run("document.querySelector('#account-menu').hidden"), false);
  assert.equal(await run("document.querySelector('.page.active').id"), 'page-projects');
  await run("document.querySelector('#account-menu-close').click(); document.dispatchEvent(new KeyboardEvent('keydown',{key:'6',ctrlKey:true,bubbles:true}))"); await delay(60);
  assert.equal(await run("document.querySelector('#account-menu').hidden"), false);
  await run("document.querySelector('#account-menu-close').click(); document.querySelector('#tab-settings').click(); document.querySelector('#tab-settings-menu [data-settings-panel=budgeting]').onclick()");
  assert.equal(await run("document.querySelector('#settings-budgeting').classList.contains('hidden')"), false);
  assert.equal(await run("document.querySelector('.page.active').id"), 'page-projects');
  await run(`(async () => { await selectAgent(await reachApi.agents.get(${JSON.stringify(fixture.id)})); await showTab('agents'); document.querySelector('#btn-agent-settings').click(); await document.querySelector('#btn-agent-settings-menu [data-settings-panel=conversation]').onclick(); })()`);
  assert.equal(await run("document.querySelector('#agent-set-name').value"), 'Menu fixture');
  await run("document.querySelector('#agent-set-name').value='Pending name'; document.querySelector('#agent-set-name').dispatchEvent(new Event('input',{bubbles:true})); document.querySelector('#agent-set-model').value='Pending model'; document.querySelector('#agent-set-model').dispatchEvent(new Event('change',{bubbles:true})); document.querySelector('#account-menu-close').click(); openSettingsPanel('conversation')");
  assert.equal(await run("document.querySelector('#agent-set-name').value"), 'Pending name');
  assert.equal(await run("document.querySelector('#agent-set-model').value"), 'Pending model');
  assert.equal(await run("document.querySelector('.page.active').id"), 'page-agents');
  await run("document.querySelector('#btn-agent-set-save').onclick()");
  assert.equal((await run(`reachApi.agents.get(${JSON.stringify(fixture.id)})`)).name, 'Pending name');
  await run("document.querySelector('#btn-agent-set-cancel').click()");
  assert.equal(await run("document.querySelector('#account-menu').hidden"), true);
  assert.equal(await run("document.querySelector('.page.active').id"), 'page-agents');
  win.webContents.send('account:state', account); await delay(60);
  win.setContentSize(1100, 900);
  await run("document.documentElement.dataset.theme='light'; ReachAccountMenu.open('account')"); await delay(80);
  fs.writeFileSync(path.join(dir, 'account-light.png'), (await win.capturePage()).toPNG());
  assert.deepEqual(errors, []);
  console.log('ACCOUNT UI PASS', dir); clearTimeout(timeout); app.exit(0);
})().catch(error => { console.error(error.stack); clearTimeout(timeout); app.exit(1); });
