#!/usr/bin/env node
'use strict';
/*
 * Generates renderer/languages.js from the RUNTIME ICU data.
 *
 * Every language name comes from Intl.DisplayNames, so it is the CLDR name for
 * that language, and the native form is what the language calls itself. That
 * means no third-party dataset to vendor or keep in sync: the list is derived
 * from the same ICU that Chromium/Node ship, and re-running this after an
 * ICU upgrade refreshes the names.
 *
 * Use:
 *   node scripts/build-languages.cjs            # write renderer/languages.js
 *   node scripts/build-languages.cjs --check    # fail if the file is stale
 */
const fs = require('node:fs');
const path = require('node:path');

const OUT = path.join(__dirname, '..', 'renderer', 'languages.js');

// The widely used languages that have no ISO 639-1 code. The 2-letter sweep
// below cannot reach them, and they are common enough to be worth listing.
const EXTRA = [
  'zh-Hans', 'zh-Hant', 'pt-BR', 'pt-PT', 'en-GB', 'es-419', 'sr-Latn',
  'fil', 'ceb', 'haw', 'yue', 'nan', 'hak', 'wuu', 'gan', 'hsn', 'lzh', 'cdo',
  'ilo', 'war', 'pam', 'pag', 'bik', 'bho', 'mai', 'hne', 'mag', 'raj', 'gom',
  'brx', 'mwr', 'awa', 'tcy', 'sat', 'doi', 'kok', 'mni', 'ks', 'arz', 'apc',
  'ary', 'aeb', 'shu', 'zgh', 'tzm', 'shi', 'kab', 'rif', 'nqo', 'tpi', 'bi',
  'sm', 'to', 'fj', 'ty', 'mi', 'ch', 'gil', 'pau', 'yap', 'pon', 'kos', 'mh',
  'niu', 'tkl', 'tv', 'kl', 'iu', 'cr', 'oj', 'nv', 'chr', 'lkt', 'moh', 'osa',
  'dak', 'cho', 'mus', 'kri', 'jam', 'srn', 'ht', 'pap', 'kea', 'mfe', 'gsw',
  'bar', 'ksh', 'pfl', 'nds', 'hsb', 'dsb', 'csb', 'szl', 'sli', 'rup', 'rm',
  'fur', 'lij', 'lmo', 'vec', 'scn', 'nap', 'pms', 'egl', 'rgn', 'sdc', 'ext',
  'mwl', 'ast', 'oc', 'frp', 'co', 'sc', 'wa', 'pcd', 'vls', 'zea', 'li', 'fy',
  'frr', 'frs', 'stq', 'tlh', 'eo', 'ia', 'ie', 'vo', 'jbo', 'lfn', 'avk', 'nov',
];

const english = new Intl.DisplayNames(['en'], { type: 'language' });

function nameOf(code) {
  try {
    const name = english.of(code);
    return name && name.toLowerCase() !== code.toLowerCase() ? name : null;
  } catch { return null; }
}

function nativeOf(code) {
  try {
    const name = new Intl.DisplayNames([code], { type: 'language' }).of(code);
    return name && name.toLowerCase() !== code.toLowerCase() ? name : null;
  } catch { return null; }
}

function build() {
  const found = new Map();
  // Every ISO 639-1 code the runtime knows.
  for (let first = 97; first <= 122; first++) {
    for (let second = 97; second <= 122; second++) {
      const code = String.fromCharCode(first, second);
      const name = nameOf(code);
      if (name) found.set(code, name);
    }
  }
  // Plus the 3-letter and regional codes 639-1 cannot express.
  for (const code of EXTRA) {
    const name = nameOf(code);
    if (name && !found.has(code)) found.set(code, name);
  }
  return [...found.entries()]
    .map(([code, name]) => ({ code, name, native: nativeOf(code) || name }))
    .sort((a, b) => a.name.localeCompare(b.name, 'en'));
}

function render(rows) {
  const escape = value => String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  const table = rows.map(row =>
    `  ['${escape(row.code)}', '${escape(row.name)}', '${escape(row.native)}'],`).join('\n');
  return `/* Reach Studio — language catalog for the message Translate action.
 *
 * GENERATED by scripts/build-languages.cjs from the runtime ICU data via
 * Intl.DisplayNames: every name is the CLDR name for that language and every
 * native form is what the language calls itself. That keeps the catalog in step
 * with the engine instead of vendoring a third-party dataset.
 *
 * ${rows.length} languages (the ISO 639-1 set plus the widely used 3-letter and
 * regional codes). Re-run the script after an ICU upgrade to refresh names.
 * Do not hand-edit.
 */
(function expose(factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (typeof window !== 'undefined') window.ReachLanguages = api;
})(function buildLanguages() {
  // [bcp47, English name, native name]
  const ROWS = [
${table}
  ];
  const LANGUAGES = ROWS.map(([code, name, native]) => Object.freeze({ code, name, native }));

  // Case-insensitive lookup by tag, English name, or native name, so a value
  // saved by an older build still resolves.
  const INDEX = new Map();
  for (const language of LANGUAGES) {
    for (const key of [language.code, language.name, language.native]) {
      INDEX.set(key.toLowerCase(), language);
    }
  }

  const DEFAULT_TARGETS = Object.freeze(['en', 'es', 'fr', 'de', 'pt', 'it', 'zh-Hans', 'ja', 'ar', 'hi']);

  function get(code) {
    return (code && INDEX.get(String(code).toLowerCase())) || null;
  }

  function displayName(code, inLocale) {
    const language = get(code);
    if (!language) return code ? String(code) : '';
    try {
      const localized = new Intl.DisplayNames([inLocale || 'en'], { type: 'language' }).of(language.code);
      if (localized && localized.toLowerCase() !== language.code.toLowerCase()) return localized;
    } catch { /* fall through to the catalog name */ }
    return language.name;
  }

  // Languages whose name or native name starts with the query, then contains it.
  // Empty query returns the head of the alphabetical list.
  function search(query, limit = 60) {
    const needle = String(query || '').trim().toLowerCase();
    if (!needle) return LANGUAGES.slice(0, limit);
    const starts = [];
    const contains = [];
    for (const language of LANGUAGES) {
      const code = language.code.toLowerCase();
      const name = language.name.toLowerCase();
      const native = language.native.toLowerCase();
      if (name.startsWith(needle) || native.startsWith(needle) || code === needle) starts.push(language);
      else if (name.includes(needle) || native.includes(needle) || code.includes(needle)) contains.push(language);
      if (starts.length + contains.length > limit * 4) break;
    }
    return [...starts, ...contains].slice(0, limit);
  }

  return Object.freeze({ LANGUAGES, DEFAULT_TARGETS, get, displayName, search });
});
`;
}

const rows = build();
const source = render(rows);
const check = process.argv.includes('--check');
if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== source) {
    console.error(`languages.js is stale — run: node ${path.relative(process.cwd(), __filename)}`);
    process.exit(1);
  }
  console.log(`languages.js is current (${rows.length} languages)`);
} else {
  fs.writeFileSync(OUT, source);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} — ${rows.length} languages, ${source.length} bytes`);
}