"""Generate browser habitat frames from the authoritative CLI renderer."""
import base64
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.reach_cli.pet_pixels import render_pixel_pet, _sprite, _fit
from tools.reach_cli.pets import PET_NAMES

BEHAVIORS = ('looking grooming stretching sleeping curious strolling walking_to_bowl snacking walking_back resting typing pondering speaking searching reading working celebrating settling petting treating forgiving refusing sulking').split()

def generate():
    result = {}
    for kind in PET_NAMES:
        result[kind] = {}
        for behavior in BEHAVIORS:
            for angry in (False, True):
                for frame in range(8):
                    drawing = _fit(_sprite(kind, behavior, frame), 34, 12)
                    travel = 34 - len(drawing[0])
                    for direction in (1, -1):
                        for food in ((1, 2, 3) if behavior == 'snacking' else (3,)):
                            frames = []
                            for x in range(travel + 1):
                                rows = render_pixel_pet(dict(kind=kind, behavior=behavior, frame=frame, direction=direction, food=food, position=x / travel if travel else 0, mood='angry' if angry else 'content'), 22, 3)
                                # Braille masks encode the same 44x12 CLI dot canvas losslessly.
                                frames.append(base64.b64encode(bytes(ord(c)-0x2800 if c != ' ' else 0 for row in rows for c in row)).decode('ascii'))
                            result[kind][f'{behavior}/{int(angry)}/{frame}/{direction}/{food}'] = frames
    return "/* Generated by scripts/build-cli-pet.py from CLI pet artwork. */\nwindow.ReachCliPetFrames=" + json.dumps(result, separators=(',', ':')) + ';\n'

if __name__ == '__main__':
    target = ROOT / 'studio/renderer/cli-pet-frames.js'
    output = generate()
    if '--check' in sys.argv:
        if target.read_text(encoding='utf8') != output:
            raise SystemExit('CLI pet frames are stale')
        print('CLI pet frames match the original renderer')
    else:
        target.write_text(output, encoding='utf8')
        print(f'Generated {target}: {len(output)} bytes')
